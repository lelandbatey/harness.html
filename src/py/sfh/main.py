def die(msg, code=1):
    print("sfh: " + msg, file=sys.stderr)
    sys.exit(code)


# --- embedded db helpers (direct mode) ---

def db_from_bytes(data):
    con = sqlite3.connect(":memory:", isolation_level=None)
    if data:
        if hasattr(con, "deserialize"):
            con.deserialize(data)
        else:  # python < 3.11
            with tempfile.NamedTemporaryFile(suffix=".sqlite") as f:
                f.write(data)
                f.flush()
                src = sqlite3.connect(f.name)
                src.backup(con)
                src.close()
    return con


def db_to_bytes(con):
    if hasattr(con, "serialize"):
        return con.serialize()
    with tempfile.TemporaryDirectory() as d:
        p = os.path.join(d, "db.sqlite")
        dst = sqlite3.connect(p)
        con.backup(dst)
        dst.close()
        with open(p, "rb") as f:
            return f.read()


def load_db(html):
    return db_from_bytes(htmlfile.read_data(html))


def save_db(html, con):
    htmlfile.write_data(html, db_to_bytes(con))


def has_table(con, name):
    return con.execute("SELECT 1 FROM sqlite_master WHERE type='table' AND name=?", (name,)).fetchone() is not None


def run_sql(con, sql, params=(), write=False):
    con.execute("PRAGMA query_only=%d" % (0 if write else 1))
    try:
        cur = con.execute(sql, params)
        cols = [d[0] for d in cur.description] if cur.description else []
        return {"columns": cols, "rows": [list(r) for r in cur.fetchall()]}
    finally:
        con.execute("PRAGMA query_only=0")


def jsonable(v):
    if isinstance(v, (bytes, bytearray, memoryview)):
        return "<blob %d bytes>" % len(v)
    return v


def print_result(res, as_json):
    rows = [[jsonable(v) for v in r] for r in res.get("rows") or []]
    if as_json:
        print(json.dumps({"columns": res.get("columns") or [], "rows": rows}, indent=1))
        return
    if res.get("columns"):
        print("\t".join(res["columns"]))
    for r in rows:
        print("\t".join("NULL" if v is None else str(v).replace("\t", " ").replace("\n", "\\n") for v in r))


# --- commands ---

def cmd_help(html, args):
    from sfh import about
    print(USAGE % {"version": common.VERSION, "file": shq(html), "about": about.text(),
                   "creds": os.path.join(common.config_dir(), "credentials")}, end="")


def shq(s):
    return s if re.fullmatch(r"[\w./@:+-]+", s) else "'" + s.replace("'", "'\\''") + "'"


def cmd_info(html, args):
    port = common.find_server(html)
    data = htmlfile.read_data(html)
    info = {"path": html, "version": common.VERSION, "file_size": os.path.getsize(html), "db_size": len(data),
            "server_running": port is not None, "port": port, "candidate_ports": common.candidate_ports(html)}
    con = db_from_bytes(data)
    if has_table(con, "sessions"):
        info["sessions"] = con.execute("SELECT count(*) FROM sessions").fetchone()[0]
    if has_table(con, "messages"):
        info["messages"] = con.execute("SELECT count(*) FROM messages").fetchone()[0]
    for k, v in info.items():
        print("%-16s %s" % (k, v))


def cmd_sql(html, args):
    flags = {a for a in args if a in ("--write", "--json")}
    rest = [a for a in args if a not in flags]
    if not rest:
        die('usage: sql "QUERY" [--write] [--json] [PARAM ...]', 2)
    sql, params = rest[0], rest[1:]
    write = "--write" in flags
    port = common.find_server(html)
    try:
        if port:
            res = common.api(port, html, "POST", "/api/sql", {"sql": sql, "params": params, "write": write})
        else:
            con = load_db(html)
            res = run_sql(con, sql, params, write)
            if write:
                save_db(html, con)
    except sqlite3.Error as e:
        die("sql error: %s" % e)
    except urllib.error.HTTPError as e:
        if e.code == 401:
            raise
        die("server error %d: %s" % (e.code, e.read().decode("utf-8", "replace")))
    print_result(res, "--json" in flags)


def cmd_db_extract(html, args):
    if len(args) != 1:
        die("usage: db-extract OUT.sqlite", 2)
    port = common.find_server(html)
    if port:
        print("note: the server is running; the file holds the last saved state", file=sys.stderr)
    data = htmlfile.read_data(html)
    with open(args[0], "wb") as f:
        f.write(data)
    print("wrote %s (%d bytes)" % (args[0], len(data)))


def cmd_db_inject(html, args):
    if len(args) != 1:
        die("usage: db-inject IN.sqlite", 2)
    if common.find_server(html):
        die("the server for this file is running; stop it first")
    with open(args[0], "rb") as f:
        data = f.read()
    if data and not data.startswith(b"SQLite format 3\0"):
        die("%s is not a sqlite database" % args[0])
    htmlfile.write_data(html, data)
    print("injected %s (%d bytes)" % (args[0], len(data)))


def program_files():
    """{relpath: source} of the original python sources (bundled or from the dev tree)."""
    bundle = sys.modules.get("_sfh_bundle")
    loader = getattr(bundle, "_sfh_loader", None)
    if loader is not None:
        return loader.original_sources()
    out = {}
    import tremolo
    import sfh
    for pkg in (sfh, tremolo):
        pkg_dir = os.path.dirname(os.path.abspath(pkg.__file__))
        base = os.path.dirname(pkg_dir)
        for dirpath, dirnames, filenames in os.walk(pkg_dir):
            dirnames[:] = [d for d in dirnames if d != "__pycache__"]
            for fn in filenames:
                if fn.endswith(".py"):
                    p = os.path.join(dirpath, fn)
                    with open(p, encoding="utf-8") as f:
                        out[os.path.relpath(p, base).replace(os.sep, "/")] = f.read()
    return out


FILE_MARK = re.compile(r"^/\*--SFH-FILE: (.+?)--\*/$", re.M)


def web_files(src):
    """Splits the inline <style>/<script> assets of the html back into files."""
    out = {}
    m = re.search(r"<style>\n(.*?)\n</style>", src, re.S)
    blocks = [m.group(1)] if m else []
    end = src.rfind(htmlfile.DATA_BEGIN)
    s = src.rfind("\n<script>\n", 0, end)
    if s >= 0:
        blocks.append(src[s + 10:src.find("\n</script>", s)])
    for text in blocks:
        marks = list(FILE_MARK.finditer(text))
        for i, mk in enumerate(marks):
            stop = marks[i + 1].start() if i + 1 < len(marks) else len(text)
            out[os.path.basename(mk.group(1))] = text[mk.end() + 1:stop].rstrip("\n") + "\n"
    b = src.find("<body>\n")
    e = src.find('<script type="text/x-python"', b)
    if b >= 0 and e > b:
        out["body.html"] = src[b + 7:e]
    return out


def cmd_extract_program(html, args):
    if len(args) != 1:
        die("usage: extract-program DIR", 2)
    d = args[0]
    files = dict(program_files())
    files.update({"web/" + k: v for k, v in web_files(htmlfile.read(html)).items()})
    for rel, text in sorted(files.items()):
        p = os.path.join(d, rel)
        os.makedirs(os.path.dirname(p), exist_ok=True)
        with open(p, "w", encoding="utf-8") as f:
            f.write(text)
    print("wrote %d files to %s\nrun with: PYTHONPATH=%s python3 -m sfh %s"
          % (len(files), d, shq(os.path.abspath(d)), shq(html)))


SETTINGS_DDL = "CREATE TABLE IF NOT EXISTS settings(key TEXT PRIMARY KEY, value TEXT)"


def settings_defaults():
    try:
        from sfh import store
    except ImportError:
        return {}
    return dict(getattr(store, "SETTINGS_DEFAULTS", {}))


def cmd_settings(html, args):
    op = args[0] if args else "get"
    if op not in ("get", "set") or (op == "set" and len(args) != 3) or (op == "get" and len(args) > 2):
        die("usage: settings [get [KEY] | set KEY JSON]", 2)
    if op == "set":
        try:
            value = json.loads(args[2])
        except ValueError:
            die("value must be JSON (strings need quotes: '\"text\"')", 2)
    port = common.find_server(html)
    if port:
        def sql(q, params=(), write=False):
            return common.api(port, html, "POST", "/api/sql", {"sql": q, "params": list(params), "write": write})
    else:
        con = load_db(html)

        def sql(q, params=(), write=False):
            return run_sql(con, q, params, write)
    if op == "set":
        sql(SETTINGS_DDL, write=True)
        sql("INSERT OR REPLACE INTO settings(key, value) VALUES(?, ?)", (args[1], json.dumps(value)), write=True)
        if not port:
            save_db(html, con)
    if port is None and not has_table(con, "settings"):
        rows = []
    else:
        rows = sql("SELECT key, value FROM settings ORDER BY key")["rows"]
    settings = dict(settings_defaults())
    settings.update({k: json.loads(v) if v is not None else None for k, v in rows})
    if op == "get" and len(args) == 2:
        if args[1] not in settings:
            die("setting %r is not set and has no default" % args[1])
        print(json.dumps(settings[args[1]], indent=1))
    else:
        print(json.dumps(settings if op == "get" else {args[1]: settings.get(args[1])}, indent=1, sort_keys=True))


def cmd_export(html, args):
    view = None
    if "--view" in args:
        i = args.index("--view")
        if i + 1 >= len(args):
            die("--view needs a value", 2)
        view = args[i + 1]
        args = args[:i] + args[i + 2:]
    if len(args) != 1:
        die("usage: export OUT.html [--view session:ID]", 2)
    out = os.path.abspath(args[0])
    if out == html:
        die("refusing to export over the file itself")
    port = common.find_server(html)
    if port:
        q = {"path": html}
        if view:
            q["view"] = view
        req = urllib.request.Request("http://127.0.0.1:%d/api/export?%s" % (port, urllib.parse.urlencode(q)),
                                     headers=common.auth_headers(html))
        with urllib.request.urlopen(req, timeout=120) as r:
            text = r.read().decode("utf-8")
            warning = r.headers.get("X-SFH-Warning")
        if warning:
            print("sfh: warning: " + warning, file=sys.stderr)
    else:
        src = htmlfile.read(html)
        con = db_from_bytes(htmlfile.decode_data(src))
        settings = dict(con.execute("SELECT key, value FROM settings").fetchall()) if has_table(con, "settings") else {}
        try:
            embedded = json.loads(settings.get("credentials_storage") or "null") == "embedded"
        except ValueError:
            embedded = False
        if has_table(con, "credentials"):
            if embedded:
                if con.execute("SELECT count(*) FROM credentials").fetchone()[0]:
                    print("sfh: warning: export contains embedded credentials", file=sys.stderr)
            else:
                con.execute("DELETE FROM credentials")
        if view is not None:
            con.execute(SETTINGS_DDL)
            con.execute("INSERT OR REPLACE INTO settings(key, value) VALUES('ui.initial_view', ?)", (json.dumps(view),))
        text = htmlfile.encode_data(src, db_to_bytes(con) if con.total_changes else htmlfile.decode_data(src))
    if htmlfile.TOKEN_RE.search(text):
        text = htmlfile.encode_token(text, "")
    htmlfile.write_atomic(out, text)
    print("exported %s (%d bytes)" % (args[0], len(text.encode("utf-8"))))


def cmd_token(html, args):
    if args not in ([], ["regenerate"]):
        die("usage: token [regenerate]", 2)
    if not args:
        tok = htmlfile.read_token(html)
        if not tok:
            die("this file has no access token yet; the server generates one on its first start")
        print(tok)
        return
    port = common.find_server(html)
    if port:
        from sfh import wsclient
        rpc = wsclient.RPC.connect(port, html)
        try:
            rpc.call("auth.regenerate")
        except wsclient.RPCError as e:
            die("regenerate failed: %s" % e)
        except wsclient.AuthError:
            pass  # the server closes every socket (code 4001) right after replying
        finally:
            try:
                rpc.close()
            except OSError:
                pass
        tok = htmlfile.read_token(html)
    else:
        import secrets
        tok = secrets.token_urlsafe(24)
        src = htmlfile.read(html)
        try:
            text = htmlfile.encode_token(src, tok)
        except ValueError as e:
            die(str(e))
        htmlfile.write_atomic(html, text)
        con = load_db(html)   # the token now belongs to this host/user/path
        con.execute("CREATE TABLE IF NOT EXISTS meta(key TEXT PRIMARY KEY, value TEXT)")
        con.execute("INSERT OR REPLACE INTO meta(key, value) VALUES('fingerprint', ?)", (common.fingerprint(html),))
        con.commit()
        save_db(html, con)
    print(tok)
    print("access token regenerated; reload open browser pages and re-run terminal clients", file=sys.stderr)


def cmd_serve(html, args):
    port = common.find_server(html)
    if port:
        die("the server for this file is already running on http://127.0.0.1:%d" % port)
    from sfh.server import serve
    serve(html, args)


def cmd_tui(html, args):
    from sfh.tui import run
    run(html, args)


COMMANDS = {"serve": cmd_serve, "tui": cmd_tui, "help": cmd_help, "--help": cmd_help, "-h": cmd_help,
            "info": cmd_info, "sql": cmd_sql, "db-extract": cmd_db_extract, "db-inject": cmd_db_inject,
            "extract-program": cmd_extract_program, "settings": cmd_settings, "export": cmd_export,
            "token": cmd_token}


def main(argv):
    if not argv:
        die("usage: main(argv) needs the html path as argv[0]", 2)
    html = common.html_path(argv[0])
    args = list(argv[1:])
    if "--mock" in args[:1]:
        args.pop(0)
        os.environ["SFH_MOCK"] = "1"
    cmd = args.pop(0) if args else "serve"
    fn = COMMANDS.get(cmd)
    if fn is None:
        print("sfh: unknown command %r\n" % cmd, file=sys.stderr)
        cmd_help(html, [])
        sys.exit(2)
    try:
        fn(html, args)
    except KeyboardInterrupt:
        sys.exit(130)
    except urllib.error.HTTPError as e:
        if e.code != 401:
            raise
        die(common.TOKEN_CHANGED)
    except ConnectionError as e:
        from sfh import wsclient
        if not isinstance(e, wsclient.AuthError):
            raise
        die(common.TOKEN_CHANGED)
    except BrokenPipeError:
        pass
